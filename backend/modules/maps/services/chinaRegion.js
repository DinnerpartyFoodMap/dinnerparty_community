const ROWS = new Map(AMAP_GCJ_CELLS);

/** 该点是否在高德的“境内”格子里；不在时高德逆地理编码不会返回省市。 */
function isInAmapChinaRegion(lng, lat) {
    if (!Number.isFinite(lng) || !Number.isFinite(lat)) return false;
    const cell = Math.floor(lng);
    const runs = ROWS.get(Math.floor(lat));
    return !!runs && runs.some(([from, to]) => from <= cell && to >= cell);
}

